/**
 * The seeded recipe base.
 *
 * This is the product's moat. A generic recipe API can return "jollof rice";
 * it cannot tell you to fry the base until the oil floats, or that the rice
 * should sit level with the water and no higher. These are written the way a
 * Nigerian home cook would explain them to someone in their kitchen.
 *
 * Every ingredient carries a `catalogueId`, which is what the matcher runs on —
 * matching on names alone would break the moment a cook typed "atarodo".
 *
 * `optional: true` means the meal is still itself without it. Optional
 * ingredients never count as missing, so a cook is not told they cannot make
 * jollof because they are out of bay leaves.
 */

type SeedIngredient = [catalogueId: string, name: string, qty: number | null, unit: string | null, optional?: boolean];

