/** Expanded to the document shape at seed time. */
export function buildSeedMeals(): Omit<MealAttributes, '_id' | 'createdAt' | 'updatedAt'>[] {
  return SEEDS.map((seed) => {
    const ingredients: MealIngredient[] = seed.ingredients.map(([catalogueId, name, quantity, unit, optional]) => ({
      catalogueId,
      name,
      quantity,
      unit,
      optional: optional ?? false,
    }));

    const steps: MealStep[] = seed.steps.map(([heading, description, estMinutes], i) => ({
      index: i + 1,
      heading,
      description,
      estMinutes,
    }));

    return {
      slug: seed.slug,
      name: seed.name,
      source: 'seed' as const,
      status: 'published' as const,
      cuisines: seed.cuisines,
      difficulty: seed.difficulty,
      cookTimeMinutes: seed.cookTimeMinutes,
      serves: seed.serves,
      whatMakesItGood: seed.whatMakesItGood,
      description: seed.description,
      ingredients,
      steps,
      // Denormalised so matching is a set operation rather than a nested scan.
      ingredientKeys: ingredients.map((i) => i.catalogueId).filter((id): id is string => id !== null),
      heroIcon: seed.heroIcon,
      createdBy: null,
    };
  });
}

